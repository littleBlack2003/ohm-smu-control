def detect_language():
    """Windows 界面语言为中文时返回 "zh"，否则 "en"。"""
    try:
        import ctypes
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        return "zh" if lang_id & 0x3FF == 0x04 else "en"
    except Exception:
        import locale
        return "zh" if (locale.getlocale()[0] or "").lower().startswith(("zh", "chinese")) else "en"
